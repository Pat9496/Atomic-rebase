#!/usr/bin/env bash
set -euo pipefail
IFS=$'\n\t'

# shellcheck source=SCRIPTDIR/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

require_not_root

usage() {
    printf 'Usage: %s --to <%s> [--from <backup-dir> | --no-migrate] [--fresh-sway-config] [-y|--yes]\n' \
        "$(basename "${BASH_SOURCE[0]}")" "$(known_desktops | paste -sd'|')" >&2
}

target_desktop=""
from_dir=""
fresh_sway_config=0
no_migrate=0
ASSUME_YES="${ASSUME_YES:-0}"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --to)
            [[ $# -ge 2 ]] || { err "--to requires an argument."; exit 1; }
            target_desktop="$2"
            shift 2
            ;;
        --from)
            [[ $# -ge 2 ]] || { err "--from requires an argument."; exit 1; }
            from_dir="$2"
            shift 2
            ;;
        --fresh-sway-config)
            fresh_sway_config=1
            shift
            ;;
        --no-migrate)
            no_migrate=1
            shift
            ;;
        -y|--yes)
            ASSUME_YES=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            err "Unknown argument: $1"
            usage
            exit 1
            ;;
    esac
done

if ! is_known_desktop "${target_desktop}"; then
    err "You must specify --to <desktop>."
    usage
    exit 1
fi

if ((fresh_sway_config)) && [[ "${target_desktop}" != "sway" ]]; then
    err "--fresh-sway-config only applies with --to sway."
    exit 1
fi

if ((no_migrate)); then
    if [[ "${target_desktop}" != "sway" ]]; then
        err "--no-migrate only applies with --to sway; for other targets there is nothing to restore without a backup."
        exit 1
    fi
    if [[ -n "${from_dir}" ]]; then
        err "--no-migrate and --from cannot be combined."
        exit 1
    fi
fi

if ((!no_migrate)) && [[ -z "${from_dir}" ]]; then
    from_dir="$(latest_backup_dir)"
fi

if ((!no_migrate)); then
    if [[ ! -d "${from_dir}" ]]; then
        err "Backup directory not found: ${from_dir}"
        exit 1
    fi
    log "Using backup: ${from_dir}"

    settings_file="${from_dir}/settings.env"
    if [[ ! -f "${settings_file}" ]]; then
        err "No settings.env found in ${from_dir}"
        exit 1
    fi
fi

SOURCE_DESKTOP=""
DARK_MODE=""
WALLPAPER_PATH=""
ACCENT_COLOR=""
INPUT_LAYOUTS=""
NIGHT_LIGHT=""
NIGHT_LIGHT_TEMP=""
IDLE_LOCK=""
IDLE_DELAY_SECONDS=""
KEY_REPEAT_DELAY_MS=""
KEY_REPEAT_INTERVAL_MS=""
TERMINAL_CMD=""
if ((no_migrate)); then
    log "Not migrating any settings (--no-migrate)."
else
    load_settings_file "${settings_file}"
    log "Settings were captured on: ${SOURCE_DESKTOP:-unknown desktop}"
fi

applied=()
skipped=()
manual_notes=()

readonly SWAY_DROPIN_MARKER="# atomic-rebase: generated by restore-config.sh, overwritten on every restore run."
sway_dropin_lines=()
sway_dropin_items=()
sway_dropin_state="none"
sway_tmp_file=""
SWAY_KEYBOARD_VARIANT=""
SWAY_OUTPUT_SCALE=""
SWAY_TOUCHPAD_TAP=""
SWAY_TOUCHPAD_NATURAL_SCROLL=""
trap '[[ -z "${sway_tmp_file}" ]] || rm -f -- "${sway_tmp_file}"' EXIT

# Sway reads the first main config it finds and never merges them, so the
# user's own ~/.config/sway/config is never touched. Everything lands in a
# single generated drop-in instead, which Fedora's /etc/sway/config includes
# last (sorted by name), so its settings win over the defaults.
#
# A value only reaches the drop-in if it can be double-quoted safely: sway
# expands $variables inside quotes and a newline ends a command, so the
# characters below are refused rather than escaped. The comma, semicolon,
# '#' and braces are refused too because they are command/comment/block
# syntax and the quoting rules for them were not worth betting a config on.
sway_value_is_quotable() {
    local value="$1"
    [[ -n "${value}" ]] || return 1
    case "${value}" in
        *[[:cntrl:]]*|*'"'*|*"'"*|*"\\"*|*'$'*|*'`'*|*';'*|*','*|*'#'*|*'{'*|*'}'*) return 1 ;;
    esac
}

# TERMINAL_CMD is only a hint from the source desktop (GNOME's key is
# deprecated, and gnome-terminal/konsole/kgx are bound to their desktop's
# stack and normally absent from the Sway image). Pointing Mod+Return at a
# binary that does not exist would silently break the terminal shortcut, so
# the name is accepted only if it resolves to an executable on this system;
# otherwise Fedora's default (foot) stays in place. ptyxis is a standalone
# terminal and passes the same check like any other. type -P is used rather
# than command -v so that shell builtins and functions never match.
sway_terminal_is_available() {
    local name="$1"
    settings_value_is_valid TERMINAL_CMD "${name}" || return 1
    ! is_terminal_launcher_name "${name}" || return 1
    [[ -n "$(type -P -- "${name}" 2>/dev/null || true)" ]]
}

sway_dropin_add_item() {
    local item
    for item in "${sway_dropin_items[@]}"; do
        [[ "${item}" == "$1" ]] && return 0
    done
    sway_dropin_items+=("$1")
}

sway_dropin_covers() {
    local item
    [[ "${sway_dropin_state}" == "active" ]] || return 1
    for item in "${sway_dropin_items[@]}"; do
        [[ "${item}" == "$1" ]] && return 0
    done
    return 1
}

# Sway has no settings UI and these values are not captured from any other
# desktop, so a first start with Fedora's defaults would come up with a US
# layout, unscaled HiDPI outputs and a touchpad without tap-to-click. Asking
# once here is what makes the switch usable without editing the config by hand.
ask_text() {
    local reply=""
    read -r -p "$1 " reply || true
    reply="${reply#"${reply%%[![:space:]]*}"}"
    ask_reply="${reply%"${reply##*[![:space:]]}"}"
}

ask_yes_no_skip() {
    local reply=""
    while true; do
        read -r -p "$1 [y/n/Enter=skip] " reply || reply=""
        case "${reply}" in
            [yY]|[yY][eE][sS]) ask_reply="true"; return 0 ;;
            [nN]|[nN][oO]) ask_reply="false"; return 0 ;;
            "") ask_reply=""; return 0 ;;
            *) warn "Please answer y, n or press Enter to skip." ;;
        esac
    done
}

ask_sway_questions() {
    local default_hint=""

    if [[ "${ASSUME_YES}" == "1" || ! -t 0 ]]; then
        log "Non-interactive run; skipping the Sway setup questions."
        return 0
    fi

    log "A few questions to set up sway. Press Enter to keep the shown value or to skip."

    default_hint=""
    [[ -z "${INPUT_LAYOUTS}" ]] || default_hint=" [${INPUT_LAYOUTS}]"
    while true; do
        ask_text "Keyboard layout(s) as xkb names, comma-separated (e.g. us, ch, de, ch,de)${default_hint}:"
        if [[ -z "${ask_reply}" ]] || settings_value_is_valid INPUT_LAYOUTS "${ask_reply}"; then
            break
        fi
        warn "Use letters, digits, '_' and '-' only, separated by commas."
    done
    [[ -z "${ask_reply}" ]] || INPUT_LAYOUTS="${ask_reply}"

    if [[ -n "${INPUT_LAYOUTS}" ]]; then
        while true; do
            ask_text "Keyboard variant(s), one per layout and comma-separated, empty for none (e.g. nodeadkeys for ch):"
            if [[ -z "${ask_reply}" || "${ask_reply}" =~ ^[A-Za-z0-9_-]*(,[A-Za-z0-9_-]*)*$ ]]; then
                break
            fi
            warn "Use letters, digits, '_' and '-' only, separated by commas."
        done
        SWAY_KEYBOARD_VARIANT="${ask_reply}"
    fi

    while true; do
        ask_text "Display scaling factor for all outputs (e.g. 1, 1.25, 1.5, 2); empty keeps sway's automatic default:"
        if [[ -z "${ask_reply}" ]]; then
            break
        fi
        if [[ "${ask_reply}" =~ ^[0-9](\.[0-9]{1,2})?$ ]] && awk -v v="${ask_reply}" 'BEGIN { exit !(v >= 0.5 && v <= 4) }'; then
            SWAY_OUTPUT_SCALE="${ask_reply}"
            break
        fi
        warn "Enter a number between 0.5 and 4, e.g. 1.5."
    done

    ask_yes_no_skip "Touchpad: enable tap-to-click?"
    SWAY_TOUCHPAD_TAP="${ask_reply}"
    ask_yes_no_skip "Touchpad: enable natural (reversed) scrolling?"
    SWAY_TOUCHPAD_NATURAL_SCROLL="${ask_reply}"

    if [[ -z "${DARK_MODE}" ]]; then
        ask_yes_no_skip "Use the dark color scheme for GTK apps?"
        DARK_MODE="${ask_reply}"
    fi
}

build_sway_dropin() {
    local keyboard_lines=() rate=""

    if [[ -n "${INPUT_LAYOUTS}" ]]; then
        if settings_value_is_valid INPUT_LAYOUTS "${INPUT_LAYOUTS}"; then
            keyboard_lines+=("    xkb_layout \"${INPUT_LAYOUTS}\"")
            [[ -z "${SWAY_KEYBOARD_VARIANT}" ]] || keyboard_lines+=("    xkb_variant \"${SWAY_KEYBOARD_VARIANT}\"")
            sway_dropin_add_item "keyboard layout"
        else
            warn "Keyboard layout list is not safe to write into a sway config; skipping."
        fi
    fi
    if [[ -n "${KEY_REPEAT_DELAY_MS}" ]]; then
        if [[ "${KEY_REPEAT_DELAY_MS}" =~ ^[0-9]{1,5}$ ]]; then
            keyboard_lines+=("    repeat_delay ${KEY_REPEAT_DELAY_MS}")
            sway_dropin_add_item "keyboard repeat rate"
        else
            warn "Key repeat delay (${KEY_REPEAT_DELAY_MS}ms) is out of range for the sway config; skipping it."
        fi
    fi
    if [[ -n "${KEY_REPEAT_INTERVAL_MS}" ]]; then
        rate="$(awk -v ms="${KEY_REPEAT_INTERVAL_MS}" 'BEGIN { if (ms > 0) printf "%d", (1000 / ms) + 0.5 }')"
        if [[ "${rate}" =~ ^[0-9]{1,4}$ ]] && ((10#${rate} >= 1)); then
            keyboard_lines+=("    repeat_rate ${rate}")
            sway_dropin_add_item "keyboard repeat rate"
        else
            warn "Key repeat interval (${KEY_REPEAT_INTERVAL_MS}ms) does not convert to a valid sway repeat_rate; skipping it."
        fi
    fi
    if ((${#keyboard_lines[@]})); then
        sway_dropin_lines+=("input type:keyboard {" "${keyboard_lines[@]}" "}")
    fi

    if [[ -n "${SWAY_TOUCHPAD_TAP}" || -n "${SWAY_TOUCHPAD_NATURAL_SCROLL}" ]]; then
        local touchpad_lines=()
        if [[ -n "${SWAY_TOUCHPAD_TAP}" ]]; then
            touchpad_lines+=("    tap $([[ "${SWAY_TOUCHPAD_TAP}" == "true" ]] && echo enabled || echo disabled)")
        fi
        if [[ -n "${SWAY_TOUCHPAD_NATURAL_SCROLL}" ]]; then
            touchpad_lines+=("    natural_scroll $([[ "${SWAY_TOUCHPAD_NATURAL_SCROLL}" == "true" ]] && echo enabled || echo disabled)")
        fi
        sway_dropin_lines+=("input type:touchpad {" "${touchpad_lines[@]}" "}")
        sway_dropin_add_item "touchpad"
    fi

    if [[ -n "${SWAY_OUTPUT_SCALE}" ]]; then
        sway_dropin_lines+=("output * scale ${SWAY_OUTPUT_SCALE}")
        sway_dropin_add_item "display scaling"
    fi

    if [[ -n "${WALLPAPER_PATH}" ]]; then
        if [[ "${WALLPAPER_PATH}" != /* ]]; then
            warn "Wallpaper path is not absolute (${WALLPAPER_PATH}); not written to the sway config."
        elif ! sway_value_is_quotable "${WALLPAPER_PATH}"; then
            warn "Wallpaper path contains characters that cannot be quoted safely in a sway config; not written."
        elif [[ ! -f "${WALLPAPER_PATH}" || ! -r "${WALLPAPER_PATH}" ]]; then
            warn "Wallpaper file ${WALLPAPER_PATH} does not exist or is unreadable on this system; not written to the sway config."
        else
            sway_dropin_lines+=("output * bg \"${WALLPAPER_PATH}\" fill")
            sway_dropin_add_item "wallpaper"
        fi
    fi

    # exec_always runs on every sway start and reload, so the GTK
    # color-scheme is reapplied each session instead of relying on a single
    # gsettings call made during this restore run.
    case "${DARK_MODE}" in
        true)
            sway_dropin_lines+=("exec_always gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark'")
            sway_dropin_add_item "dark mode"
            ;;
        false)
            sway_dropin_lines+=("exec_always gsettings set org.gnome.desktop.interface color-scheme 'default'")
            sway_dropin_add_item "dark mode"
            ;;
    esac
    if [[ "${ACCENT_COLOR}" =~ ^[a-z]+$ ]]; then
        sway_dropin_lines+=("exec_always gsettings set org.gnome.desktop.interface accent-color '${ACCENT_COLOR}'")
        sway_dropin_add_item "accent color"
    fi

    if [[ -n "${TERMINAL_CMD}" ]]; then
        if sway_terminal_is_available "${TERMINAL_CMD}"; then
            sway_dropin_lines+=("set \$term ${TERMINAL_CMD}" "bindsym \$mod+Return exec ${TERMINAL_CMD}")
            sway_dropin_add_item "default terminal"
        else
            warn "Terminal '${TERMINAL_CMD}' from the source desktop is not available on this system; leaving Sway's default terminal in place."
            manual_notes+=("Default terminal: the source desktop used '${TERMINAL_CMD}', which is not installed here, so Sway's default terminal (foot) was left unchanged. To use another one, add 'set \$term <binary>' and 'bindsym \$mod+Return exec <binary>' to a file in ~/.config/sway/config.d/ that sorts after 99-atomic-rebase.conf (e.g. 99-local.conf).")
        fi
    fi
}

write_sway_dropin() {
    local dropin_dir="${HOME}/.config/sway/config.d"
    local dropin_file="${dropin_dir}/99-atomic-rebase.conf"
    local main_config="${HOME}/.config/sway/config" first_line="" tmp=""

    if ((${#sway_dropin_lines[@]} == 0)); then
        sway_dropin_state="none"
        log "Nothing to write to a sway drop-in."
        return 0
    fi

    if [[ -e "${dropin_file}" || -L "${dropin_file}" ]]; then
        if [[ -f "${dropin_file}" ]]; then
            IFS= read -r first_line < "${dropin_file}" || true
        fi
        if [[ "${first_line}" != "${SWAY_DROPIN_MARKER}" ]]; then
            warn "${dropin_file} exists but was not generated by atomic-rebase; not overwriting it."
            manual_notes+=("Sway: ${dropin_file} already existed and was not generated by atomic-rebase, so the migrated Sway settings were not written. Move it away and run restore-config.sh again.")
            sway_dropin_state="failed"
            return 1
        fi
    fi

    if ! mkdir -p -- "${dropin_dir}"; then
        warn "Could not create ${dropin_dir}."
        sway_dropin_state="failed"
        return 1
    fi
    if ! tmp="$(mktemp -- "${dropin_dir}/.99-atomic-rebase.conf.XXXXXX")"; then
        warn "Could not create a temporary file in ${dropin_dir}."
        sway_dropin_state="failed"
        return 1
    fi
    sway_tmp_file="${tmp}"

    if ! {
        printf '%s\n' "${SWAY_DROPIN_MARKER}"
        printf '%s\n' "# Put local overrides in a file that sorts after this one, e.g. 99-local.conf."
        printf '%s\n' "${sway_dropin_lines[@]}"
    } > "${tmp}" || ! chmod 600 -- "${tmp}" || ! mv -f -- "${tmp}" "${dropin_file}"; then
        warn "Could not write ${dropin_file}."
        sway_dropin_state="failed"
        return 1
    fi
    sway_tmp_file=""
    log "Wrote sway drop-in ${dropin_file}"

    if [[ -e "${main_config}" ]] && ! grep -Eq '^[[:space:]]*include[[:space:]].*config\.d' "${main_config}"; then
        warn "${main_config} exists but does not include config.d, so Sway will not load ${dropin_file}."
        manual_notes+=("Sway: ${main_config} takes precedence over /etc/sway/config and has no 'config.d' include, so ${dropin_file} is NOT loaded. Add the line 'include ~/.config/sway/config.d/*.conf' to it (it was not modified), then reload sway.")
        sway_dropin_state="inactive"
        return 0
    fi

    sway_dropin_state="active"
    manual_notes+=("Sway: migrated settings were written to ${dropin_file}. It is regenerated on every restore run; keep your own overrides in a separately named file in that directory that sorts after it (e.g. 99-local.conf).")

    if [[ -n "${SWAYSOCK:-}" ]] && command -v swaymsg >/dev/null 2>&1; then
        if swaymsg reload >/dev/null 2>&1; then
            log "Reloaded sway to pick up the new drop-in."
        else
            warn "swaymsg reload failed; reload sway manually (default: Mod+Shift+C) to apply the drop-in."
        fi
    else
        log "No running sway session detected; the drop-in takes effect on the next sway start or reload."
    fi
}

# Sway never merges configs, so a broken ~/.config/sway/config (e.g. one
# carried over from an older install) stops the whole session from coming up
# no matter what the drop-in says. Moving it aside, not deleting it, lets
# /etc/sway/config (Fedora's default, which includes config.d) take over.
reset_sway_main_config() {
    local main_config="${HOME}/.config/sway/config" backup=""

    if [[ ! -e "${main_config}" && ! -L "${main_config}" ]]; then
        log "No ${main_config} present; sway will already use its default config."
        return 0
    fi
    if ! confirm "Move ${main_config} aside so sway starts from a fresh default config?"; then
        warn "Keeping the existing ${main_config}."
        return 0
    fi
    backup="${main_config}.bak-$(date +%Y%m%d-%H%M%S)"
    if mv -- "${main_config}" "${backup}"; then
        log "Moved ${main_config} to ${backup}"
        manual_notes+=("Sway: the previous ${main_config} was moved to ${backup}; sway now starts from /etc/sway/config plus the generated drop-in. Copy over only the parts of the old file you still want, into a file in ~/.config/sway/config.d/ that sorts after 99-atomic-rebase.conf (e.g. 99-local.conf).")
    else
        warn "Could not move ${main_config} aside; keeping it."
    fi
}

if [[ "${target_desktop}" == "sway" ]]; then
    if ((fresh_sway_config)); then
        reset_sway_main_config
    fi
    ask_sway_questions
    build_sway_dropin
    write_sway_dropin || true
fi

if ((no_migrate)); then
    for note in "${manual_notes[@]}"; do
        log "${note}"
    done
    log "Done. No settings were migrated and no backup was read."
    exit 0
fi

# Applies DARK_MODE to the target desktop's own native config mechanism.
# Returns 1 if the target has no known mechanism (currently unreachable,
# since every entry in DESKTOP_IMAGE is handled below, but kept as a guard
# in case a new desktop is added to the catalog without updating this file).
apply_dark_mode() {
    local target="$1" value="$2"
    case "${target}" in
        silverblue|budgie)
            require_cmd gsettings
            if [[ "${value}" == "true" ]]; then
                gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark'
            else
                gsettings set org.gnome.desktop.interface color-scheme 'default'
            fi
            ;;
        kinoite)
            require_cmd plasma-apply-colorscheme
            if [[ "${value}" == "true" ]]; then
                plasma-apply-colorscheme BreezeDark
            else
                plasma-apply-colorscheme BreezeClassic
            fi
            ;;
        sway)
            require_cmd gsettings
            warn "Sway has no desktop-wide dark mode; only the GTK app color-scheme is being set."
            if [[ "${value}" == "true" ]]; then
                gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark'
            else
                gsettings set org.gnome.desktop.interface color-scheme 'default'
            fi
            sway_dropin_covers "dark mode" || warn "The color-scheme was set for the running session only; it is not persisted in the sway config (see warnings above)."
            ;;
        cosmic)
            local mode_dir="${HOME}/.config/cosmic/com.system76.CosmicTheme.Mode/v1"
            mkdir -p "${mode_dir}"
            printf '%s' "${value}" > "${mode_dir}/is_dark"
            warn "Wrote ${mode_dir}/is_dark directly (COSMIC has no settings CLI); a re-login may be needed for it to take effect."
            ;;
        *)
            return 1
            ;;
    esac
}

if [[ -n "${DARK_MODE}" ]]; then
    log "Applying dark/light mode (${DARK_MODE}) to ${target_desktop}..."
    if apply_dark_mode "${target_desktop}" "${DARK_MODE}"; then
        applied+=("dark/light mode")
    else
        warn "No dark-mode mechanism defined for ${target_desktop}."
        skipped+=("dark/light mode")
    fi
else
    warn "No DARK_MODE recorded in ${settings_file}; skipping."
    skipped+=("dark/light mode")
fi

if [[ -n "${WALLPAPER_PATH}" ]]; then
    log "Applying wallpaper (${WALLPAPER_PATH}) to ${target_desktop}..."
    case "${target_desktop}" in
        silverblue)
            require_cmd gsettings
            wallpaper_uri="file://${WALLPAPER_PATH}"
            gsettings set org.gnome.desktop.background picture-uri "${wallpaper_uri}"
            gsettings set org.gnome.desktop.background picture-uri-dark "${wallpaper_uri}"
            applied+=("wallpaper")
            ;;
        kinoite)
            require_cmd plasma-apply-wallpaperimage
            plasma-apply-wallpaperimage "${WALLPAPER_PATH}"
            applied+=("wallpaper")
            ;;
        sway)
            if sway_dropin_covers "wallpaper"; then
                applied+=("wallpaper")
            else
                warn "Wallpaper was not written to the sway config (see warnings above)."
                skipped+=("wallpaper")
            fi
            ;;
        *)
            warn "No confirmed wallpaper mechanism for ${target_desktop}; skipping."
            skipped+=("wallpaper")
            ;;
    esac
else
    warn "No WALLPAPER_PATH recorded in ${settings_file}; skipping."
    skipped+=("wallpaper")
fi

# kdeglobals has no confirmed way to read the accent color back (see
# backup-config.sh), so apply_accent_color always derives the KDE base
# scheme from whatever apply_dark_mode just set (or the scheme already on
# disk if dark mode wasn't applied this run) rather than guessing one.
apply_accent_color() {
    local target="$1" value="$2"
    case "${target}" in
        silverblue|budgie)
            require_cmd gsettings
            gsettings set org.gnome.desktop.interface accent-color "${value}"
            ;;
        sway)
            require_cmd gsettings
            warn "Sway has no desktop-wide accent color; only the GTK app accent-color is being set."
            gsettings set org.gnome.desktop.interface accent-color "${value}"
            sway_dropin_covers "accent color" || warn "The accent color was set for the running session only; it is not persisted in the sway config (see warnings above)."
            ;;
        kinoite)
            require_cmd plasma-apply-colorscheme
            local kde_color="${value}"
            # GNOME's "slate" isn't a standard SVG/CSS color name; slategray
            # is the closest real one plasma-apply-colorscheme will accept.
            [[ "${kde_color}" == "slate" ]] && kde_color="slategray"
            local scheme
            scheme="$(kde_read_config --file kdeglobals --group General --key ColorScheme)"
            if [[ -z "${scheme}" ]]; then
                warn "Could not determine the current KDE color scheme; skipping accent color."
                return 1
            fi
            plasma-apply-colorscheme --accent-color "${kde_color}" "${scheme}"
            ;;
        *)
            return 1
            ;;
    esac
}

if [[ -n "${ACCENT_COLOR}" ]]; then
    log "Applying accent color (${ACCENT_COLOR}) to ${target_desktop}..."
    if apply_accent_color "${target_desktop}" "${ACCENT_COLOR}"; then
        applied+=("accent color")
    else
        warn "No accent-color mechanism defined for ${target_desktop}."
        skipped+=("accent color")
    fi
else
    warn "No ACCENT_COLOR recorded in ${settings_file}; skipping."
    skipped+=("accent color")
fi

# Applies INPUT_LAYOUTS (a comma-separated list of xkb layout codes, e.g.
# "us,de") captured from GNOME/Budgie's input-sources or KDE's kxkbrc.
# Keyboard variants (dvorak, colemak, ...) are not preserved by this tool.
apply_input_layouts() {
    local target="$1" value="$2"
    case "${target}" in
        silverblue|budgie)
            require_cmd gsettings
            local tuples="" layout first=1 layout_arr
            IFS=',' read -ra layout_arr <<< "${value}"
            for layout in "${layout_arr[@]}"; do
                [[ -n "${layout}" ]] || continue
                if ((first)); then
                    tuples="('xkb', '${layout}')"
                    first=0
                else
                    tuples="${tuples}, ('xkb', '${layout}')"
                fi
            done
            [[ -n "${tuples}" ]] || return 1
            gsettings set org.gnome.desktop.input-sources sources "[${tuples}]"
            ;;
        kinoite)
            kde_write_config --file kxkbrc --group Layout --key LayoutList "${value}"
            kde_write_config --file kxkbrc --group Layout --key Use true
            kwin_reconfigure
            warn "Wrote kxkbrc directly; a logout/login may be needed for the new keyboard layout to fully apply."
            ;;
        sway)
            sway_dropin_covers "keyboard layout"
            ;;
        *)
            return 1
            ;;
    esac
}

if [[ -n "${INPUT_LAYOUTS}" ]]; then
    log "Applying keyboard layout(s) (${INPUT_LAYOUTS}) to ${target_desktop}..."
    if apply_input_layouts "${target_desktop}" "${INPUT_LAYOUTS}"; then
        applied+=("keyboard layout")
    else
        warn "Keyboard layout(s) not applied to ${target_desktop} (no mechanism defined, or see the warnings above)."
        skipped+=("keyboard layout")
    fi
else
    warn "No INPUT_LAYOUTS recorded in ${settings_file}; skipping."
    skipped+=("keyboard layout")
fi

# Applies NIGHT_LIGHT (true/false) and, if present, NIGHT_LIGHT_TEMP (Kelvin).
apply_night_light() {
    local target="$1" enabled="$2" temp="$3"
    case "${target}" in
        silverblue|budgie)
            require_cmd gsettings
            gsettings set org.gnome.settings-daemon.plugins.color night-light-enabled "${enabled}"
            if [[ -n "${temp}" ]]; then
                gsettings set org.gnome.settings-daemon.plugins.color night-light-temperature "${temp}"
            fi
            ;;
        kinoite)
            kde_write_config --file kwinrc --group NightColor --key Active "${enabled}"
            [[ -n "${temp}" ]] && kde_write_config --file kwinrc --group NightColor --key NightTemperature "${temp}"
            kwin_reconfigure
            ;;
        *)
            return 1
            ;;
    esac
}

if [[ -n "${NIGHT_LIGHT}" ]]; then
    log "Applying night light (enabled=${NIGHT_LIGHT} temp=${NIGHT_LIGHT_TEMP:-unset}) to ${target_desktop}..."
    if apply_night_light "${target_desktop}" "${NIGHT_LIGHT}" "${NIGHT_LIGHT_TEMP}"; then
        applied+=("night light")
